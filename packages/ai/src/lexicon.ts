function buildLexicon(): ReadonlyMap<string, LexiconEntry> {
  const lexicon = new Map<string, LexiconEntry>();
  for (const [english, arabic, pos] of PHRASES) lexicon.set(english, { arabic, pos });
  for (const row of NOUNS) {
    const [english, arabic, plural] = row;
    lexicon.set(
      english,
      plural === undefined ? { arabic, pos: 'noun' } : { arabic, pos: 'noun', plural },
    );
  }
  for (const [english, arabic] of VERBS) lexicon.set(english, { arabic, pos: 'verb' });
  for (const [english, arabic] of ADJECTIVES) lexicon.set(english, { arabic, pos: 'adjective' });
  for (const [english, arabic, pos] of FUNCTION_WORDS) lexicon.set(english, { arabic, pos });
  return lexicon;
}

export const ENGLISH_TO_ARABIC: ReadonlyMap<string, LexiconEntry> = buildLexicon();

/**
 * Short vowel marks, the shadda and the superscript alif.
 *
 * Written Arabic omits them most of the time and the same word appears with and
 * without them, so they are removed before any lookup rather than doubling the
 * lexicon. The range stops short of U+0660, where the Arabic-Indic digits start.
 */
const ARABIC_DIACRITICS = /[ً-ٰٟ]/gu;

export function stripArabicDiacritics(value: string): string {
  return value.replace(ARABIC_DIACRITICS, '');
}

/**
 * The reverse index, for AR → EN.
 *
 * Built from the same rows so the two directions can never drift apart. Where
 * several English words share an Arabic rendering the first row wins, which is
 * why the tables above list the most common sense first.
 */
export const ARABIC_TO_ENGLISH: ReadonlyMap<string, string> = (() => {
  const reverse = new Map<string, string>();
  for (const [english, entry] of ENGLISH_TO_ARABIC) {
    if (!reverse.has(entry.arabic)) reverse.set(entry.arabic, english);
    if (entry.plural !== undefined && !reverse.has(entry.plural))
      reverse.set(entry.plural, english);
  }
  return reverse;
})();

/** Longest phrase in {@link PHRASES}, in words — the greedy matcher's window. */
export const MAX_PHRASE_WORDS = PHRASES.reduce(
  (longest, [english]) => Math.max(longest, english.split(' ').length),
  1,
);


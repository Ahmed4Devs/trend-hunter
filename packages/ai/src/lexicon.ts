export interface ModeStyle {
  /** Optional Arabic sentence that frames the whole translation. */
  readonly openers: readonly string[];
  /** Connectors inserted between sentences from the second onwards. */
  readonly connectors: readonly string[];
  /** Sentences longer than this are split; 0 disables splitting. */
  readonly maxSentenceWords: number;
  /** Whether to apply {@link SIMPLE_ARABIC_FORMS}. */
  readonly plainVocabulary: boolean;
  /** Whether Arabic word order is repaired, or English order kept verbatim. */
  readonly repairWordOrder: boolean;
  /** Sentence separator: a newline gives the stacked look of an X post. */
  readonly sentenceSeparator: string;
}

